#!/usr/bin/env node
/**
 * Builds the Rust crates under `crates/` into the WebAssembly packages the
 * TypeScript code imports:
 *
 *   crates/open-artifact-wb-geom   → packages/wasm-wb-geom/generated/   Whiteboard geometry
 *   crates/open-artifact-export    → packages/wasm-export/generated/    export packing (zip, PDF, PNG), run in a Worker
 *   crates/open-artifact-canvas    → packages/wasm-canvas/generated/    the WebGL2 canvas engine
 *   crates/open-artifact-data-rules → packages/wasm-data-rules/generated/ Data rule patterns (linear-time matching)
 *   crates/open-artifact-sheets    → packages/wasm-sheets/generated/    the Sheets workbook engine, run in a Worker
 *   crates/open-artifact-motion    → packages/wasm-motion/generated/    Motion GIF and MOV encoding, flash analysis
 *
 * Each package gets the wasm-bindgen glue (`<crate>.js` + `.d.ts`) and the
 * optimized module embedded as base64 (`bytes.js`), so it loads
 * synchronously everywhere the TypeScript runs: Node tests, the bundled CLI
 * and the editor pages, with no asset to serve or path to resolve. A crate
 * marked `file` is too large to embed: its module is written beside the glue
 * (`<crate>_bg.wasm`), and the page fetches it while Node reads it from disk.
 *
 * The output is committed: building the editors or running the tests does
 * not need a Rust toolchain. Run this after changing a crate.
 *
 * Needs: cargo with the wasm32-unknown-unknown target, wasm-bindgen (the
 * same version as the crate's `wasm-bindgen` dependency) and wasm-opt.
 *
 * Usage: node scripts/build-wasm.mjs [crate…]
 */

import { execFileSync } from 'node:child_process';
import { mkdir, mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');

/** Crate → the package folder it is built into, and how wasm-opt optimizes it. */
const CRATES = {
  'open-artifact-wb-geom': { pkg: 'packages/wasm-wb-geom', opt: '-O3' },
  'open-artifact-export': { pkg: 'packages/wasm-export', opt: '-O3' },
  'open-artifact-canvas': { pkg: 'packages/wasm-canvas', opt: '-O3' },
  'open-artifact-data-rules': { pkg: 'packages/wasm-data-rules', opt: '-Oz' },
  'open-artifact-sheets': { pkg: 'packages/wasm-sheets', opt: '-O3', file: true },
  'open-artifact-motion': { pkg: 'packages/wasm-motion', opt: '-O3' },
};

const FEATURES = ['--enable-bulk-memory', '--enable-nontrapping-float-to-int', '--enable-sign-ext', '--enable-mutable-globals', '--enable-reference-types', '--enable-multivalue'];

const run = (cmd, args) => execFileSync(cmd, args, { cwd: ROOT, stdio: ['ignore', 'inherit', 'inherit'] });

const wanted = process.argv.slice(2);
for (const [crate, { pkg, opt, file = false }] of Object.entries(CRATES)) {
  if (wanted.length > 0 && !wanted.includes(crate)) continue;
  const lib = crate.replaceAll('-', '_');
  const started = performance.now();
  run('cargo', ['build', '--release', '--target', 'wasm32-unknown-unknown', '-p', crate]);
  const temp = await mkdtemp(join(tmpdir(), `${crate}-`));
  try {
    run('wasm-bindgen', [join(ROOT, 'target/wasm32-unknown-unknown/release', `${lib}.wasm`), '--out-dir', temp, '--target', 'web', '--omit-default-module-path', '--no-typescript']);
    run('wasm-bindgen', [join(ROOT, 'target/wasm32-unknown-unknown/release', `${lib}.wasm`), '--out-dir', join(temp, 'types'), '--target', 'web', '--omit-default-module-path']);
    const optimized = join(temp, `${lib}.opt.wasm`);
    run('wasm-opt', [opt, ...FEATURES, join(temp, `${lib}_bg.wasm`), '-o', optimized]);
    const bytes = await readFile(optimized);
    const out = join(ROOT, pkg, 'generated');
    await rm(out, { recursive: true, force: true });
    await mkdir(out, { recursive: true });
    const header = `// Generated by scripts/build-wasm.mjs from crates/${crate}. Do not edit.\n`;
    await writeFile(join(out, `${lib}.js`), header + (await readFile(join(temp, `${lib}.js`), 'utf8')));
    await writeFile(join(out, `${lib}.d.ts`), header + (await readFile(join(temp, 'types', `${lib}.d.ts`), 'utf8')));
    if (file) {
      await writeFile(join(out, `${lib}_bg.wasm`), bytes);
    } else {
      await writeFile(join(out, 'bytes.js'), `${header}export const WASM_BASE64 = '${bytes.toString('base64')}';\n`);
      await writeFile(join(out, 'bytes.d.ts'), `${header}/** The optimized module, base64. */\nexport declare const WASM_BASE64: string;\n`);
    }
    console.log(`${crate} → ${pkg}/generated (${(bytes.length / 1024).toFixed(1)} KB wasm) in ${((performance.now() - started) / 1000).toFixed(1)}s`);
  } finally {
    await rm(temp, { recursive: true, force: true });
  }
}

/** Words with `{name}` placeholders filled. */
export type Translate = (key: Key, params?: Record<string, string>) => string;

/** Fills `{name}` placeholders. */
export function fill(text: string, params: Record<string, string> = {}): string {
  return text.replace(/\{(\w+)\}/g, (whole, name: string) => params[name] ?? whole);
}

/** English, for when the host has no locale service. */
export const fallbackTranslate: Translate = (key, params) => fill(en[key] ?? key, params);

/** A translate function of the host's (`ctx.locale.bind(ns)`), or the fallback. */
export function translator(bound: ((key: string, params?: Record<string, string>) => string) | undefined): Translate {
  if (typeof bound !== 'function') return fallbackTranslate;
  return (key, params) => {
    const text = bound(key, params);
    // A host that leaves the placeholders to the caller, or does not know the key.
    return typeof text === 'string' && text !== key ? fill(text, params) : fallbackTranslate(key, params);
  };
}
